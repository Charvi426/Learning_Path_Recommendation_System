def build(name: str, execute: bool = True):
    nb = nbf.v4.new_notebook()
    for kind, src in NB[name]:
        nb.cells.append(nbf.v4.new_markdown_cell(src) if kind == "md" else nbf.v4.new_code_cell(src))
    out = HERE / f"{name}.ipynb"
    nbf.write(nb, out)
    if execute:
        subprocess.run([sys.executable, "-m", "jupyter", "nbconvert", "--to", "notebook", "--execute",
                        "--inplace", "--ExecutePreprocessor.timeout=900", "--ExecutePreprocessor.kernel_name=fds312", str(out)], check=True, cwd=HERE)


if __name__ == "__main__":
    which = sys.argv[1:] or ["01", "02", "03", "04"]
    for n in NB:
        if n[:2] in which:
            build(n)
            print("built", n)
