def render(t: RC.Table) -> str:
    env = "table*" if t.wide else "table"
    spec = SPEC.get(t.key, "@{}l" + "l" * (len(t.columns) - 1) + "@{}")
    body = []
    for r in t.rows:
        cols = [num(v.text()) if isinstance(v, Val) else label(str(v)) for v in r]
        body.append(" & ".join(cols) + r" \\")
    size = r"\scriptsize" if len(t.columns) >= 4 else r"\footnotesize"
    return "\n".join([
        "% generated by report/make_tables.py - do not edit",
        "% sources: " + ", ".join(t.sources),
        rf"\begin{{{env}}}[!t]",
        r"\centering",
        rf"\caption{{{label(t.title)}. {label(CAPTION_STATUS[t.key])}{FLAG[t.key]}}}",
        rf"\label{{tab:{t.key.replace('_', '-')}}}",
        size,
        r"\setlength{\tabcolsep}{3pt}",
        rf"\begin{{tabular}}{{{spec}}}",
        r"\toprule",
        " & ".join(HEAD.get(c, label(c)) for c in t.columns) + r" \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\vspace{2pt}\parbox{\linewidth}{\scriptsize" + " " + label(t.validity) + "}",
        rf"\end{{{env}}}",
        "",
    ])


