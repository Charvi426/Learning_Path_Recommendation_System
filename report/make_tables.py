def main():
    OUT.mkdir(parents=True, exist_ok=True)
    prov = []

    def record(where, v: Val):
        for c in (v.est, v.lo, v.hi):
            if c is None:
                continue
            raw = RC.read(c)
            if isinstance(raw, float) and raw != raw:
                continue
            prov.append({"used_in": where, "file": c.file, "col": c.col,
                         "where": [[k, str(x)] for k, x in c.where], "style": v.style, "text": RC.fmt(raw, v.style)})

    tables = RC.tables()
    for key, t in tables.items():
        (OUT / f"{key}.tex").write_text(render(t), encoding="utf-8", newline="\n")
        for i, r in enumerate(t.rows):
            for j, v in enumerate(r):
                if isinstance(v, Val):
                    record(f"table:{key}:{i}:{j}", v)
    nums = prose_numbers()
    lines = ["% generated by report/make_tables.py - do not edit"]
    for name, v in nums.items():
        lines.append(rf"\newcommand{{\{name}}}{{\mbox{{{num(v.text())}}}}}")
        record(f"macro:{name}", v)
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    (OUT / "provenance.json").write_text(json.dumps(prov, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(tables)} tables, {len(nums)} prose numbers, {len(prov)} traced values -> report/tables/")


if __name__ == "__main__":
    main()
