def esc(s: str) -> str:
    for a, b in (("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_")):
        s = s.replace(a, b)
    return s


def num(s: str) -> str:
    """Typeset a formatted value: real minus signs, unbreakable."""
    s = esc(s).replace("<", "$<$")
    if s == "--":
        return s
    return s.replace("-", "$-$").replace("+", "$+$")


def label(s: str) -> str:
    return esc(s).replace("K = M*R", "$K=MR$").replace("M*R", "$MR$")


